// Generates TEACHERS.md deterministically from data/teachers.json, works.json, citations.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const load = (f) => JSON.parse(readFileSync(join(root, 'data', f), 'utf8'));
const teachers = load('teachers.json').teachers;
const works = load('works.json').works;
const citations = load('citations.json').citations;

const ref = (r) => `${r.book} ${r.chapter}:${r.verseStart}${r.verseEnd !== r.verseStart ? `-${r.verseEnd}` : ''}`;
const byYear = (a, b) => (a.year ?? 9999) - (b.year ?? 9999) || a.title.localeCompare(b.title);

const out = [
  '# Teachers, works and timeline',
  '',
  '> Generated by `npm run build:teachers` from `data/teachers.json`, `works.json` and `citations.json`. Do not edit by hand.',
  '> Bibliographic only: no quoted or paraphrased text. A citation marked unverified has not been checked against its URL.',
  '',
  '## Timeline',
  '',
  '| Year | Basis | Author | Work | Copyright |',
  '|---|---|---|---|---|',
];
const name = (id) => teachers.find((t) => t.id === id)?.name ?? id;
for (const w of [...works].sort(byYear)) out.push(`| ${w.year ?? '?'} | ${w.yearBasis} | ${name(w.teacherId)} | [${w.title}](${w.sourceUrl}) | ${w.copyright} |`);
if (!works.length) out.push('| _none yet_ | | | | |');

out.push('', '## Authors', '');
for (const t of [...teachers].sort((a, b) => (a.born ?? 9999) - (b.born ?? 9999))) {
  out.push(`### ${t.name} (${t.born ?? '?'}–${t.died ?? '?'})`, '', `Dates source: ${t.sourceUrl}`, '');
  for (const w of works.filter((x) => x.teacherId === t.id).sort(byYear)) {
    out.push(`- **${w.title}** (${w.year ?? '?'}, ${w.yearBasis}${w.edition ? `; ${w.edition}` : ''}) — ${w.sourceUrl}`);
    for (const c of citations.filter((x) => x.workId === w.id)) {
      out.push(`  - ${c.location} → ${c.addresses.map(ref).join('; ')} — [link](${c.url}) — ${c.verified ? `verified ${c.verifiedOn}` : 'UNVERIFIED'}`);
    }
  }
  out.push('');
}
if (!teachers.length) out.push('_No authors recorded yet._', '');
writeFileSync(join(root, 'TEACHERS.md'), out.join('\n'));
console.log('TEACHERS.md written');
